@pytest.fixture
def repo(lab_repo: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """The lab repo where the reader data product builds its table with dbt."""
    # No orchestrator builds dbt tables into a DAG yet, so a fake one stands in.
    register(monkeypatch, "orchestrator", "fake", FakeOrchestrator)
    (lab_repo / "datapatchbay.yaml").write_text("schema_version: 1\norchestrator: fake\n")
    write(lab_repo, "dbt_project.yml", "name: lab\nversion: '1.0.0'\nprofile: lab\nmodel-paths: ['models']\n")
    product = lab_repo / DP / "dataproduct.yaml"
    product.write_text(product.read_text() + "executor: dbt\n")
    write(lab_repo, TABLE, TABLE_YAML)
    write(lab_repo, MODEL, "select 1 as days\n")
    return lab_repo


def files(repo: Path) -> dict[str, str]:
    loaded, report = load_and_validate(repo)
    assert report.ok, [p.render() for p in report.problems]
    settings = load_settings(repo)
    plans = plan_dataproducts(loaded, settings)
    return {str(f.path): f.content for f in generate_dbt_properties(plans, settings)}


def owner_of(repo: Path) -> str:
    for line in (repo / DP / "dataproduct.yaml").read_text().splitlines():
        if line.startswith("owner:"):
            return line.split(": ", 1)[1]
    raise AssertionError("no owner")


def test_a_dbt_table_gets_properties_next_to_its_model(repo: Path):
    write(repo, TABLE, TABLE_FILE)
    assert files(repo)[f"{DP}/models/agg_lab_turnaround__turnaround.yml"] == PROPERTIES


def test_a_data_product_with_a_dbt_table_gets_a_group_with_its_owner(repo: Path):
    assert files(repo)[f"{DP}/models/_group.yml"] == GROUPS.replace("OWNER", owner_of(repo))


def test_python_tables_get_no_properties(lab_repo: Path):
    assert files(lab_repo) == {}


def test_the_same_input_gives_identical_output(repo: Path):
    write(repo, TABLE, TABLE_FILE)
    assert files(repo) == files(repo)


def test_generate_writes_the_properties_into_the_repo(repo: Path):
    generate_repo(repo)
    assert (repo / DP / "models/agg_lab_turnaround__turnaround.yml").read_text().startswith("# Generated by")
    assert (repo / DP / "models/_group.yml").is_file()


def test_a_second_run_leaves_the_files_byte_identical(repo: Path):
    write(repo, TABLE, TABLE_FILE)
    generate_repo(repo)
    first = {p: p.read_bytes() for p in (repo / DP / "models").glob("*.yml")}
    generate_repo(repo)
    assert first
    assert first == {p: p.read_bytes() for p in (repo / DP / "models").glob("*.yml")}


def test_a_failing_orchestrator_writes_no_properties(repo: Path, monkeypatch: pytest.MonkeyPatch):
    def fail(self, plan, context):
        raise UnsupportedCombinationError("nope")

    monkeypatch.setattr(FakeOrchestrator, "generate", fail)
    with pytest.raises(GenerationError, match="nope"):
        generate_repo(repo)
    assert list((repo / DP / "models").glob("*.yml")) == []


def test_a_failing_dbt_project_sync_writes_no_properties(repo: Path):
    (repo / "dbt_project.yml").write_text("- not a mapping\n")
    with pytest.raises(GenerationError, match=r"dbt_project\.yml"):
        generate_repo(repo)
    assert list((repo / DP / "models").glob("*.yml")) == []


@pytest.mark.dbt
def test_dbt_parses_the_generated_properties(repo: Path, tmp_path: Path):
    dbt = shutil.which("dbt")
    if dbt is None and os.environ.get("DPB_REQUIRE_DBT"):
        pytest.fail("dbt is missing but DPB_REQUIRE_DBT is set, so this test would silently not run")
    if dbt is None:
        pytest.skip("dbt is not installed; CI runs this test with `--group dbt`")
    write(repo, TABLE, TABLE_FILE)
    for path, content in files(repo).items():
        write(repo, path, content)
    write(repo, "dbt_project.yml", f"name: lab\nversion: '1.0.0'\nprofile: lab\nmodel-paths: ['{DP}/models']\n")
    profiles = tmp_path / "profiles"
    write(
        profiles,
        "profiles.yml",
        "lab:\n  target: dev\n  outputs:\n    dev:\n"
        "      {type: postgres, host: localhost, user: u, password: p, port: 5432, dbname: d, schema: s, threads: 1}\n",
    )
    result = subprocess.run(
        [dbt, "parse", "--project-dir", str(repo), "--profiles-dir", str(profiles)],
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    manifest = json.loads((repo / "target" / "manifest.json").read_text())
    model = manifest["nodes"]["model.lab.agg_lab_turnaround__turnaround"]
    assert model["config"]["contract"]["enforced"] is True
    assert model["group"] == "agg_lab_turnaround"
    assert model["alias"] == "turnaround"
    assert model["schema"].endswith(model["config"]["schema"])
    tests = [n for n in manifest["nodes"].values() if n["resource_type"] == "test"]
    assert {t["config"]["severity"].lower() for t in tests} <= {"error", "warn"}
    assert {t["test_metadata"]["name"] for t in tests} == {"not_null", "unique", "accepted_values"}
