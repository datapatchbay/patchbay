def two_readers(lab_dbt_repo: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """Both `agg_lab_turnaround` and `agg_lab_weekly` build with dbt, and both read `sa_ilab_orders`."""
    register(monkeypatch, "orchestrator", "fake", FakeOrchestrator)
    (lab_dbt_repo / "datapatchbay.yaml").write_text("schema_version: 1\norchestrator: fake\n")
    product = lab_dbt_repo / DP / "dataproduct.yaml"
    product.write_text(product.read_text() + "executor: dbt\n")
    write(lab_dbt_repo, TABLE, TABLE_YAML)
