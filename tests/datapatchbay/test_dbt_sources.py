from pathlib import Path

import pytest
from dbt_helpers import DP, MODEL, TABLE, TABLE_YAML, planned, rendered, write
from plugin_fakes import FakeOrchestrator, register

from datapatchbay.dbt_sources import generate_dbt_sources
from datapatchbay.generate import generate_repo

PRODUCER = "dataproducts/sa_jaffle_orders"
ORDERS = f"{PRODUCER}/outputs/sa_jaffle_orders/orders.yaml"
SOURCES = f"{DP}/models/_sources.yml"
WEEKLY_SOURCES = "dataproducts/agg_weekly_orders/models/_sources.yml"

ORDERS_FILE = """\
schema_version: 1
name: orders
description: One row per jaffle shop order
columns:
  - name: order_id
    type: text
    description: The order
    rules: [not_null, unique]
  - name: customer_id
    type: text
    pii: true
build:
  entrypoint: src/orders.py:build
  needs: [ingested_orders]
rules:
  - rule: row_count
    min: 1
"""

EXPECTED = f"""\
# Generated by datapatchbay from {ORDERS}. Do not edit: `dpb generate` overwrites this file.
sources:
  - name: sa_jaffle_orders
    schema: sa_jaffle_orders
    tables:
      - name: orders
        description: One row per jaffle shop order
        columns:
          - name: order_id
            description: The order
          - name: customer_id
"""


@pytest.fixture
def repo(jaffle_repo: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """The jaffle shop repo where the reader `agg_order_turnaround` builds with dbt and reads `sa_jaffle_orders`."""
    register(monkeypatch, "orchestrator", "fake", FakeOrchestrator)
    (jaffle_repo / "datapatchbay.yaml").write_text("schema_version: 1\norchestrator: fake\n")
    write(
        jaffle_repo,
        "dbt_project.yml",
        "name: jaffle_shop\nversion: '1.0.0'\nprofile: jaffle_shop\nmodel-paths: ['models']\n",
    )
    product = jaffle_repo / DP / "dataproduct.yaml"
    product.write_text(product.read_text() + "executor: dbt\n")
    write(jaffle_repo, TABLE, TABLE_YAML)
    write(jaffle_repo, MODEL, "select 1 as days\n")
    write(jaffle_repo, ORDERS, ORDERS_FILE)
    return jaffle_repo


def sources(repo: Path) -> dict[str, str]:
    return {str(f.path): f.content for f in generate_dbt_sources(planned(repo).plans)}


def test_an_input_port_that_reads_a_data_product_becomes_a_dbt_source(repo: Path):
    assert sources(repo) == {SOURCES: EXPECTED}


def test_the_same_input_gives_identical_sources(repo: Path):
    assert sources(repo) == sources(repo)


def test_a_data_product_not_built_by_dbt_gets_no_sources(jaffle_repo: Path):
    assert sources(jaffle_repo) == {}


@pytest.fixture
def two_readers(jaffle_dbt_repo: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """Both `agg_order_turnaround` and `agg_weekly_orders` build with dbt, and both read `sa_jaffle_orders`."""
    register(monkeypatch, "orchestrator", "fake", FakeOrchestrator)
    (jaffle_dbt_repo / "datapatchbay.yaml").write_text("schema_version: 1\norchestrator: fake\n")
    product = jaffle_dbt_repo / DP / "dataproduct.yaml"
    product.write_text(product.read_text() + "executor: dbt\n")
    write(jaffle_dbt_repo, TABLE, TABLE_YAML)
    write(jaffle_dbt_repo, MODEL, "select 1 as days\n")
    return jaffle_dbt_repo


def test_one_port_read_by_several_data_products_is_written_once_in_the_first_by_name(two_readers: Path):
    written = sources(two_readers)
    assert list(written) == [SOURCES]  # agg_order_turnaround sorts before agg_weekly_orders
    assert "name: sa_jaffle_orders" in written[SOURCES]


def test_the_first_reader_that_dbt_builds_owns_the_source(two_readers: Path):
    product = two_readers / DP / "dataproduct.yaml"
    product.write_text(product.read_text().replace("executor: dbt\n", ""))
    write(two_readers, TABLE, TABLE_YAML + "build: {entrypoint: src/turnaround.py:build}\n")
    assert list(sources(two_readers)) == [WEEKLY_SOURCES]


def test_generate_writes_the_sources_into_the_repo(repo: Path):
    generate_repo(repo)
    assert (repo / SOURCES).read_text() == EXPECTED


def test_generated_sources_pass_validate(repo: Path):
    generate_repo(repo)
    assert rendered(repo) == []


def test_a_changed_producer_table_file_makes_the_sources_stale(repo: Path):
    generate_repo(repo)
    write(repo, ORDERS, ORDERS_FILE.replace("columns:\n", "columns:\n  - name: extra\n    type: text\n"))
    [problem] = rendered(repo)
    assert problem.startswith(f"{SOURCES}: ")
    assert "dpb generate" in problem


def test_a_missing_sources_file_fails(repo: Path):
    generate_repo(repo)
    (repo / SOURCES).unlink()
    [problem] = rendered(repo)
    assert problem.startswith(f"{SOURCES}: ")
    assert "missing" in problem


def test_hand_edited_sources_fail(repo: Path):
    generate_repo(repo)
    (repo / SOURCES).write_text("sources: []\n")
    [problem] = rendered(repo)
    assert problem.startswith(f"{SOURCES}: ")
