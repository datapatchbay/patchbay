import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest
from dbt_helpers import DP, MODEL, TABLE, TABLE_YAML, rendered, write
from plugin_fakes import FakeOrchestrator, register

from datapatchbay.dbt_sources import generate_dbt_sources
from datapatchbay.generate import generate_repo
from datapatchbay.planning import plan_dataproducts
from datapatchbay.settings import load_settings
from datapatchbay.validation import load_and_validate

PRODUCER = "dataproducts/sa_ilab_orders"
ORDERS = f"{PRODUCER}/outputs/sa_ilab_orders/orders.yaml"
SOURCES = f"{DP}/models/_sources.yml"
WEEKLY_SOURCES = "dataproducts/agg_lab_weekly/models/_sources.yml"

ORDERS_FILE = """\
schema_version: 1
name: orders
description: One row per lab order
columns:
  - name: order_id
    type: text
    description: The order
    rules: [not_null, unique]
  - name: patient_id
    type: text
    pii: true
build:
  entrypoint: src/orders.py:build
  needs: [ingested_orders]
rules:
  - rule: row_count
    min: 1
"""

EXPECTED = f"""\
# Generated by datapatchbay from {ORDERS}. Do not edit: `dpb generate` overwrites this file.
sources:
  - name: sa_ilab_orders
    schema: sa_ilab_orders
    tables:
      - name: orders
        description: One row per lab order
        columns:
          - name: order_id
            description: The order
          - name: patient_id
"""


@pytest.fixture
def repo(lab_repo: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """The lab repo where the reader `agg_lab_turnaround` builds its table with dbt and reads `sa_ilab_orders`."""
    register(monkeypatch, "orchestrator", "fake", FakeOrchestrator)
    (lab_repo / "datapatchbay.yaml").write_text("schema_version: 1\norchestrator: fake\n")
    write(lab_repo, "dbt_project.yml", "name: lab\nversion: '1.0.0'\nprofile: lab\nmodel-paths: ['models']\n")
    product = lab_repo / DP / "dataproduct.yaml"
    product.write_text(product.read_text() + "executor: dbt\n")
    write(lab_repo, TABLE, TABLE_YAML)
    write(lab_repo, MODEL, "select 1 as days\n")
    write(lab_repo, ORDERS, ORDERS_FILE)
    return lab_repo


def sources(repo: Path) -> dict[str, str]:
    loaded, report = load_and_validate(repo)
    assert report.ok, [p.render() for p in report.problems]
    settings = load_settings(repo)
    return {str(f.path): f.content for f in generate_dbt_sources(plan_dataproducts(loaded, settings))}


def test_an_input_port_that_reads_a_data_product_becomes_a_dbt_source(repo: Path):
    assert sources(repo) == {SOURCES: EXPECTED}


def test_the_same_input_gives_identical_sources(repo: Path):
    assert sources(repo) == sources(repo)


def test_a_data_product_not_built_by_dbt_gets_no_sources(lab_repo: Path):
    assert sources(lab_repo) == {}


