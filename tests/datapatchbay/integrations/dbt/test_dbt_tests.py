from pathlib import Path

import pytest
from dbt_helpers import DP, MODEL, TABLE, TABLE_YAML, planned, rendered, write
from plugin_fakes import FakeOrchestrator, register

from datapatchbay.generate import generate_repo
from datapatchbay.integrations.dbt.tests import generate_dbt_tests

TESTS = f"{DP}/tests"
NAME = "agg_order_turnaround__turnaround"
HEADER = f"-- Generated by datapatchbay from {TABLE}. Do not edit: `dpb generate` overwrites this file.\n"
REF = f"{{{{ ref('{NAME}') }}}}"


@pytest.fixture
def repo(jaffle_repo: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    register(monkeypatch, "orchestrator", "fake", FakeOrchestrator)
    (jaffle_repo / "datapatchbay.yaml").write_text("schema_version: 1\norchestrator: fake\n")
    write(jaffle_repo, "dbt_project.yml", "name: jaffle_shop\nversion: '1.0.0'\nprofile: jaffle_shop\n")
    product = jaffle_repo / DP / "dataproduct.yaml"
    product.write_text(product.read_text() + "executor: dbt\n")
    write(jaffle_repo, TABLE, TABLE_YAML)
    write(jaffle_repo, MODEL, "select 1 as days\n")
    return jaffle_repo


def with_rules(repo: Path, rules: str, extra: str = "") -> None:
    write(repo, TABLE, TABLE_YAML + extra + "rules:\n" + rules)


def generated_tests(repo: Path) -> dict[str, str]:
    gate = planned(repo)
    return {str(f.path): f.content for f in generate_dbt_tests(gate.plans, gate.settings)}


def test_a_primary_key_selects_null_and_repeated_keys(repo: Path):
    with_rules(repo, "  - {rule: primary_key, columns: [days, order_id]}\n", "  - name: order_id\n    type: text\n")
    assert generated_tests(repo) == {
        f"{TESTS}/{NAME}__primary_key.sql": HEADER
        + "{{ config(severity='error') }}\n\n"
        + "select\n"
        + "    {{ adapter.quote('days') }},\n"
        + "    {{ adapter.quote('order_id') }},\n"
        + "    count(*) as occurrences\n"
        + f"from {REF}\n"
        + "group by {{ adapter.quote('days') }}, {{ adapter.quote('order_id') }}\n"
        + "having {{ adapter.quote('days') }} is null or {{ adapter.quote('order_id') }} is null or count(*) > 1\n"
    }


def test_a_row_count_selects_one_row_outside_the_bounds(repo: Path):
    with_rules(repo, "  - {rule: row_count, min: 1, max: 10, severity: warning}\n")
    assert generated_tests(repo) == {
        f"{TESTS}/{NAME}__row_count.sql": HEADER
        + "{{ config(severity='warn') }}\n\n"
        + "select n\n"
        + f"from (select count(*) as n from {REF}) as counted\n"
        + "where n < 1 or n > 10\n"
    }


def test_a_row_count_with_one_bound_checks_only_that_bound(repo: Path):
    with_rules(repo, "  - {rule: row_count, max: 5}\n")
    assert generated_tests(repo)[f"{TESTS}/{NAME}__row_count.sql"].endswith("where n > 5\n")


def test_a_sql_rule_is_copied_as_written_without_its_semicolon(repo: Path):
    with_rules(repo, f"  - rule: sql\n    sql: |\n      select * from {REF} where days < 0;\n")
    assert generated_tests(repo) == {
        f"{TESTS}/{NAME}__sql.sql": HEADER
        + "{{ config(severity='error') }}\n\n"
        + f"select * from {REF} where days < 0\n"
    }


def test_further_rules_of_one_kind_get_a_numbered_suffix_in_file_order(repo: Path):
    with_rules(repo, "  - {rule: sql, sql: select 1 where false}\n  - {rule: sql, sql: select 2 where false}\n")
    generated = generated_tests(repo)
    assert sorted(generated) == [f"{TESTS}/{NAME}__sql.sql", f"{TESTS}/{NAME}__sql_2.sql"]
    assert generated[f"{TESTS}/{NAME}__sql_2.sql"].endswith("select 2 where false\n")


def test_a_rule_without_severity_takes_the_table_severity_and_none_writes_no_file(repo: Path):
    write(repo, "datapatchbay.yaml", "schema_version: 1\norchestrator: fake\nseverity: warning\n")
    with_rules(repo, "  - {rule: row_count, min: 1}\n  - {rule: sql, sql: select 1 where false, severity: none}\n")
    generated = generated_tests(repo)
    assert list(generated) == [f"{TESTS}/{NAME}__row_count.sql"]
    assert "config(severity='warn')" in generated[f"{TESTS}/{NAME}__row_count.sql"]


def test_a_table_without_table_rules_gets_no_tests(repo: Path):
    write(repo, TABLE, TABLE_YAML)
    assert generated_tests(repo) == {}


def test_a_python_table_gets_no_tests(jaffle_repo: Path):
    assert generated_tests(jaffle_repo) == {}


def test_generate_writes_the_tests_and_the_test_paths(repo: Path):
    with_rules(repo, "  - {rule: row_count, min: 1}\n")
    generate_repo(repo)
    assert (repo / TESTS / f"{NAME}__row_count.sql").read_text().startswith(HEADER)
    assert f"test-paths:\n  - {TESTS}\n" in (repo / "dbt_project.yml").read_text()
    assert rendered(repo) == []


def test_the_same_input_gives_identical_files(repo: Path):
    with_rules(repo, "  - {rule: primary_key, columns: [days]}\n  - {rule: row_count, min: 1}\n")
    assert generated_tests(repo) == generated_tests(repo)


def test_a_changed_rule_makes_the_test_stale(repo: Path):
    with_rules(repo, "  - {rule: row_count, min: 1}\n")
    generate_repo(repo)
    with_rules(repo, "  - {rule: row_count, min: 2}\n")
    [problem] = rendered(repo)
    assert problem.startswith(f"{TESTS}/{NAME}__row_count.sql: ")
    assert "dpb generate" in problem


def test_a_missing_test_file_fails(repo: Path):
    with_rules(repo, "  - {rule: row_count, min: 1}\n")
    generate_repo(repo)
    (repo / TESTS / f"{NAME}__row_count.sql").unlink()
    [problem] = rendered(repo)
    assert "missing" in problem
    assert "dpb generate" in problem


def test_a_generated_test_of_a_removed_rule_fails(repo: Path):
    with_rules(repo, "  - {rule: row_count, min: 1}\n")
    generate_repo(repo)
    write(repo, TABLE, TABLE_YAML)
    [problem] = rendered(repo)
    assert problem.startswith(f"{TESTS}/{NAME}__row_count.sql: ")
    assert "no longer" in problem


def test_a_hand_written_test_is_left_alone(repo: Path):
    generate_repo(repo)
    write(repo, f"{TESTS}/mine.sql", "select 1 where false\n")
    assert rendered(repo) == []


def test_stale_test_paths_fail(repo: Path):
    generate_repo(repo)
    write(
        repo,
        "dbt_project.yml",
        f"name: jaffle_shop\nversion: '1.0.0'\nprofile: jaffle_shop\nmodel-paths: [{DP}/models]\n",
    )
    [problem] = rendered(repo)
    assert problem.startswith("dbt_project.yml: ")
    assert "test-paths" in problem
