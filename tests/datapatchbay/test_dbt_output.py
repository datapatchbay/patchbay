"""The committed dbt output as one value: what `build_dbt_output` makes of a planned repo, before any write."""

from pathlib import Path, PurePosixPath

import pytest
from dbt_helpers import DP, MODEL, TABLE_YAML, planned, rendered, write
from plugin_fakes import FakeOrchestrator, register

from datapatchbay.dbt_output import DbtFileKind, build_dbt_output
from datapatchbay.generate import generate_repo

PROJECT = "dbt_project.yml"
TURNAROUND = f"{DP}/outputs/agg_order_turnaround/turnaround.yaml"


@pytest.fixture
def dbt_repo(jaffle_repo: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """A repo with one table built by dbt, one table rule and a root `dbt_project.yml`, not yet generated."""
    register(monkeypatch, "orchestrator", "fake", FakeOrchestrator)
    (jaffle_repo / "datapatchbay.yaml").write_text("schema_version: 1\norchestrator: fake\n")
    product = jaffle_repo / DP / "dataproduct.yaml"
    product.write_text(product.read_text() + "executor: dbt\n")
    write(jaffle_repo, TURNAROUND, TABLE_YAML + "rules:\n  - {rule: row_count, min: 1}\n")
    write(jaffle_repo, MODEL, "select 1 as days\n")
    write(jaffle_repo, PROJECT, "name: jaffle_shop\nversion: '1.0'\nprofile: jaffle_shop\n")
    return jaffle_repo


def test_every_file_is_tagged_with_its_kind(dbt_repo: Path):
    output = build_dbt_output(planned(dbt_repo))
    kinds = {file.path.name: file.kind for file in output.files}
    assert kinds == {
        "_group.yml": DbtFileKind.PROPERTIES,
        "agg_order_turnaround__turnaround.yml": DbtFileKind.PROPERTIES,
        "_sources.yml": DbtFileKind.SOURCES,
        "agg_order_turnaround__turnaround__row_count.sql": DbtFileKind.TEST,
    }
    assert [file.path for file in output.files] == sorted(file.path for file in output.files)


def test_the_project_change_lists_the_folders_of_the_data_products_built_by_dbt(dbt_repo: Path):
    output = build_dbt_output(planned(dbt_repo))
    assert output.project is not None
    assert output.project.path == dbt_repo / PROJECT
    assert f"model-paths:\n  - {DP}/models" in output.project.content
    assert f"test-paths:\n  - {DP}/tests" in output.project.content
    assert output.project_error is None


def test_a_project_in_step_has_no_change(dbt_repo: Path):
    generate_repo(dbt_repo)
    output = build_dbt_output(planned(dbt_repo))
    assert output.project is None
    assert output.orphans == ()
    assert output.problems() == []


def test_a_missing_project_is_carried_as_an_error_not_raised(dbt_repo: Path):
    (dbt_repo / PROJECT).unlink()
    output = build_dbt_output(planned(dbt_repo))
    assert output.project is None
    assert output.project_error is not None
    assert "dbt_project.yml is expected at the repo root" in output.project_error
    assert [problem.render() for problem in output.problems() if problem.file == PurePosixPath(PROJECT)] == [
        f"{PROJECT}: {output.project_error}"
    ]


def test_a_repo_without_a_dbt_table_has_an_empty_output(jaffle_repo: Path):
    output = build_dbt_output(planned(jaffle_repo))
    assert output.files == ()
    assert output.project is None
    assert output.project_error is None
    assert output.model_paths == ()
    assert output.problems() == []


def test_the_paths_come_from_the_plans(dbt_repo: Path):
    output = build_dbt_output(planned(dbt_repo))
    assert output.model_paths == (f"{DP}/models",)
    assert output.test_paths == (f"{DP}/tests",)


def test_orphans_are_generated_files_that_no_table_produces_any_more(dbt_repo: Path):
    generate_repo(dbt_repo)
    write(dbt_repo, TURNAROUND, TABLE_YAML)  # the table rule goes, and so does its test
    write(dbt_repo, f"{DP}/tests/my_own.sql", "select 1 where false\n")  # hand-written, so never an orphan
    output = build_dbt_output(planned(dbt_repo))
    assert output.orphans == (PurePosixPath(f"{DP}/tests/agg_order_turnaround__turnaround__row_count.sql"),)


def test_write_puts_files_then_deletes_orphans_then_the_project_last(dbt_repo: Path):
    generate_repo(dbt_repo)
    write(dbt_repo, TURNAROUND, TABLE_YAML + "rules:\n  - {rule: row_count, min: 2}\n  - {rule: row_count, min: 3}\n")
    write(dbt_repo, f"{DP}/tests/zz_old.sql", "-- Generated by datapatchbay from x. Do not edit: `dpb generate`.\n")
    (dbt_repo / PROJECT).write_text("name: jaffle_shop\nversion: '1.0'\nprofile: jaffle_shop\n")
    output = build_dbt_output(planned(dbt_repo))
    events: list[str] = []

    def record(path: Path, content: str) -> None:
        events.append(path.relative_to(dbt_repo).as_posix())

    committed = output.write(record)
    assert events[-1] == PROJECT
    assert [path.as_posix() for path in committed] == events
    assert output.orphans == (PurePosixPath(f"{DP}/tests/zz_old.sql"),)
    assert not (dbt_repo / output.orphans[0]).exists()


