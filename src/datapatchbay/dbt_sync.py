"""Checking that the committed dbt files still match the table files, without writing anything (ADR-0013).

The dbt properties and the `model-paths` of `dbt_project.yml` are generated by `dpb generate` and committed. This
computes them in memory, with the same functions `dpb generate` writes with, so the two cannot drift, and compares
them with the files on disk. It also finds a model declared a second time by hand.
"""

from collections.abc import Mapping, Sequence
from pathlib import Path, PurePosixPath

from ruamel.yaml.comments import CommentedSeq

from datapatchbay.dbt import MODELS_FOLDER
from datapatchbay.dbt_project import DBT_PROJECT_FILE, DbtProjectError, model_paths, synced_dbt_project
from datapatchbay.dbt_properties import GROUP_FILE
from datapatchbay.dbt_sources import SOURCES_FILE, generate_dbt_files
from datapatchbay.genheader import generated_from
from datapatchbay.planning import plan_dataproducts
from datapatchbay.plugins import GeneratedFile
from datapatchbay.problems import Problem
from datapatchbay.repomodel import Repo
from datapatchbay.settings import EffectiveSettings
from datapatchbay.yamlio import YamlLoadError, load_mapping

_REFRESH = "run `dpb generate` to refresh it"


def check_dbt_files(repo: Repo, settings: EffectiveSettings) -> list[Problem]:
    """Compare the generated dbt files with the files on disk, and look for hand-written duplicates of a model.

    Only call this for a repo whose other checks passed, because it plans the data products.

    Returns:
        The problems found, empty when dbt builds no table or the files are in step.
    """
    generated = generate_dbt_files(plan_dataproducts(repo, settings), settings)
    problems: list[Problem] = []
    for file in generated:
        path = repo.root / file.path
        if not path.is_file():
            problems.append(Problem(file.path, None, f"dbt properties file is missing; {_REFRESH}"))
        elif path.read_bytes() != file.content.encode("utf-8"):
            problems.append(Problem(file.path, None, f"dbt properties file does not match its table file; {_REFRESH}"))
    project = PurePosixPath(DBT_PROJECT_FILE)
    try:
        if synced_dbt_project(repo, settings) is not None:
            problems.append(
                Problem(
                    project,
                    None,
                    f"`model-paths` does not list the `{MODELS_FOLDER}/` folders of the data products built by dbt; "
                    f"{_REFRESH}",
                )
            )
    except DbtProjectError as exc:
        problems.append(Problem(project, None, str(exc)))
    problems.extend(
        Problem(path, None, "dbt file is no longer generated from the table files; delete it")
        for path in orphaned_dbt_properties(repo, generated)
    )
    problems.extend(_duplicates(repo, settings, generated))
    return problems


def orphaned_dbt_properties(repo: Repo, generated: Sequence[GeneratedFile]) -> list[PurePosixPath]:
    """Find the files that carry the generated header in a `models/` folder but are not in `generated`.

    These are left behind when a table is no longer built by dbt, or removed. A file without the header is
    hand-written and never an orphan.

    Returns:
        The paths relative to the repo root, sorted.
    """
    wanted = {file.path for file in generated}
    orphans = []
    for dataproduct in repo.dataproducts:
        directory = dataproduct.directory / MODELS_FOLDER
        if not directory.is_dir():
            continue
        for path in [*directory.rglob("*.yml"), *directory.rglob("*.yaml")]:
            relative = PurePosixPath(path.relative_to(repo.root).as_posix())
            if relative not in wanted and generated_from(path) is not None:
                orphans.append(relative)
    return sorted(orphans)


def _duplicates(repo: Repo, settings: EffectiveSettings, generated: Sequence[GeneratedFile]) -> list[Problem]:
    built = {file.path.stem: file.path for file in generated if file.path.name not in {GROUP_FILE, SOURCES_FILE}}
    generated_paths = {file.path for file in generated}
    problems: list[Problem] = []
    for folder in model_paths(repo, settings):
        directory = repo.root / folder
        if not directory.is_dir():
            continue
        for path in sorted([*directory.rglob("*.yml"), *directory.rglob("*.yaml")]):
            relative = PurePosixPath(path.relative_to(repo.root).as_posix())
            if relative not in generated_paths:
                problems.extend(_duplicates_in(path, relative, built))
    return problems


def _duplicates_in(path: Path, relative: PurePosixPath, built: Mapping[str, PurePosixPath]) -> list[Problem]:
    try:
        data = load_mapping(path)
    except YamlLoadError:
        return []  # not a dbt properties file, or not YAML; dbt reports its own files
    entries = data.get("models")
    if not isinstance(entries, CommentedSeq):
        return []
    problems = []
    for index, entry in enumerate(entries):
        name = entry.get("name") if hasattr(entry, "get") else None
        if isinstance(name, str) and name in built:
            problems.append(
                Problem(
                    relative,
                    entries.lc.item(index)[0] + 1,
                    f"model '{name}' is already declared in {built[name]}, which `dpb generate` writes from its "
                    "table file; remove this entry",
                )
            )
    return problems
